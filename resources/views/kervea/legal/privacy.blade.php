 <p>Üyelerimiz isterlerse Google veya LinkedIn hesabıyla giriş yapabilir. Bu durumda sağlayıcıdan yalnızca <b>e-posta adresiniz (sağlayıcı tarafından doğrulanmış olması şartıyla), adınız ve sağlayıcıdaki benzersiz kullanıcı kimliğiniz</b> alınır. Bu bilgiler yalnızca kimliğinizi doğrulamak ve mevcut üyeliğinizle eşleştirmek için kullanılır; sağlayıcı hesabınızdaki diğer verilere (kişiler, takvim, dosyalar, e-postalar vb.) erişilmez, üçüncü kişilerle paylaşılmaz ve reklam amacıyla kullanılmaz. Bu yöntemle yeni üyelik oluşturulmaz; yalnızca yönetici onayıyla açılmış üyelikler için geçerlidir. Bağlantının kaldırılması için iletişim formundan bize yazabilirsiniz.</p>
